import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "../..");
const outDir = path.join(rootDir, "contracts", "out");
const webContractsDir = path.join(rootDir, "apps", "web", "src", "contracts");
const deployPath = path.join(rootDir, "deployments", "sepolia.json");
const webDeployPath = path.join(webContractsDir, "deployment.json");
const manifestPath = path.join(rootDir, "circuits", "build", "manifest.json");

const targets = [
  { file: "HospitalRegistry.sol", name: "HospitalRegistry" },
  { file: "PolicyRegistry.sol", name: "PolicyRegistry" },
  { file: "HealthRecords.sol", name: "HealthRecords" },
  { file: "ClaimsVault.sol", name: "ClaimsVault" },
  { file: "Groth16Verifier.sol", name: "Groth16Verifier" },
];

fs.mkdirSync(webContractsDir, { recursive: true });
fs.mkdirSync(path.dirname(deployPath), { recursive: true });

const abis = {};
for (const t of targets) {
  const artifactPath = path.join(outDir, t.file, `${t.name}.json`);
  if (!fs.existsSync(artifactPath)) {
    throw new Error(`Missing compiled artifact: ${artifactPath}. Run forge build first.`);
  }
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  abis[t.name] = artifact.abi;
}

const tsOut =
  `// Auto-generated by contracts/script/export-abis.mjs — do not edit manually.\n` +
  targets
    .map((t) => `export const ${t.name}Abi = ${JSON.stringify(abis[t.name], null, 2)} as const;\n`)
    .join("\n");

fs.writeFileSync(path.join(webContractsDir, "abis.ts"), tsOut);

if (!fs.existsSync(deployPath)) {
  const manifest = fs.existsSync(manifestPath)
    ? JSON.parse(fs.readFileSync(manifestPath, "utf8"))
    : { zkeySha256: "" };
  const initialDeployment = {
    deployed: false,
    chainId: 11155111,
    network: "sepolia",
    explorerBaseUrl: "https://sepolia.etherscan.io",
    sourcifyBaseUrl: "https://repo.sourcify.dev/contracts/full_match/11155111",
    zkeySha256: manifest.zkeySha256 || "",
    seededInsurer: "0x0000000000000000000000000000000000000000",
    deployBlock: 0,
    contracts: {
      Groth16Verifier: "0x0000000000000000000000000000000000000000",
      HospitalRegistry: "0x0000000000000000000000000000000000000000",
      PolicyRegistry: "0x0000000000000000000000000000000000000000",
      HealthRecords: "0x0000000000000000000000000000000000000000",
      ClaimsVault: "0x0000000000000000000000000000000000000000",
    },
  };
  fs.writeFileSync(deployPath, JSON.stringify(initialDeployment, null, 2));
}

fs.copyFileSync(deployPath, webDeployPath);
console.log("[export-abis] Synced apps/web/src/contracts/abis.ts and deployment.json");
